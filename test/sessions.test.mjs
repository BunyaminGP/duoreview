import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { randomUUID } from "node:crypto";
const require = createRequire(import.meta.url);
const { createSessionStore, findCodexSession } = require("../app/sessions.js");
const dir = mkdtempSync(join(tmpdir(), "duoreview-sessions-"));
try {
  const data = join(dir, "data"), root = join(dir, "sessions");
  mkdirSync(root);
  let store = createSessionStore(data);
  const original = store.prepare("claude");
  store.started("claude", original);
  store = createSessionStore(data);
  assert.equal(store.prepare("claude").sessionId, original.sessionId);
  assert.equal(store.prepare("claude").resume, true);
  assert.equal(createSessionStore(join(dir, "other-project")).resumable().claude, false);
  const fresh = store.prepare("claude", true);
  assert.notEqual(fresh.sessionId, original.sessionId);
  assert.equal(fresh.resume, false);
  store.started("claude", fresh);
  assert.equal(createSessionStore(data).prepare("claude").sessionId, fresh.sessionId);
  store.forget("claude");
  assert.equal(createSessionStore(data).resumable().claude, false);
  assert.equal(store.resumable().gemini, false);

  const pending = store.prepare("codex");
  store.started("codex", pending);
  const trace = { tag: pending.sessionTag, startedAt: pending.startedAt };
  const sid = randomUUID();
  const meta = (id, cwd = dir) => ({ type: "session_meta", payload: { id, cwd } });
  const call = { type: "response_item", payload: { type: "function_call", name: "mcp__duoreview__next_action", call_id: "c1" } };
  const output = { type: "response_item", payload: { type: "function_call_output", call_id: "c1",
    output: JSON.stringify({ content: [{ type: "text", text: JSON.stringify({ action: "WAIT", session_tag: trace.tag }) }] }) } };
  const write = (name, rows) => writeFileSync(join(root, name), rows.map((r) => JSON.stringify(r)).join("\n") + "\n");
  write("rollout-external.jsonl", [meta(sid), call]);
  assert.equal(await store.discover(dir, root), false, "single external rollout is not owned");
  assert.equal(store.resumable().codex, false);
  write("rollout-external.jsonl", [meta(sid), { type: "response_item", payload: { type: "message", content: [{ text: trace.tag }] } }]);
  assert.equal(await findCodexSession(trace, dir, root), null, "tag in ordinary message is not proof");
  write("rollout-external.jsonl", [meta(sid), output]);
  assert.equal(await findCodexSession(trace, dir, root), null, "unpaired output is not proof");
  write("rollout-external.jsonl", [meta(sid, join(dir, "other")), call, output]);
  assert.equal(await findCodexSession(trace, dir, root), null, "wrong project rejected");
  write("rollout-external.jsonl", [meta(sid), call, output]);
  write("rollout-second.jsonl", [meta(randomUUID()), call, output]);
  assert.equal(await findCodexSession(trace, dir, root), null, "ambiguous trace rejected");
  write("rollout-second.jsonl", []);
  const event = { type: "event_msg", payload: { type: "item_completed", thread_id: sid,
    item: { type: "McpToolCall", server: "duoreview", tool: "next_action", status: "completed", result: JSON.parse(output.payload.output) } } };
  write("rollout-external.jsonl", [meta(sid), { ...event, payload: { ...event.payload, thread_id: randomUUID() } }]);
  assert.equal(await findCodexSession(trace, dir, root), null, "another thread's event is not ownership proof");
  write("rollout-external.jsonl", [meta(sid), { ...event, payload: { ...event.payload, item: { ...event.payload.item, tool: "status" } } }]);
  assert.equal(await findCodexSession(trace, dir, root), null, "another tool's event is not ownership proof");
  write("rollout-external.jsonl", [meta(sid), event]);
  assert.equal(await findCodexSession(trace, dir, root), sid, "current CLI's structured MCP completion is recognized");
  store = createSessionStore(data);
  assert.equal(await store.discover(dir, root), true, "pending trace survives application restart");
  assert.equal(store.prepare("codex").sessionId, sid);
  assert.equal(createSessionStore(data).resumable().codex, true);
  const freshCodex = store.prepare("codex", true);
  assert.equal(freshCodex.resume, false);
  assert.equal(freshCodex.sessionId, undefined);
  store.started("codex", freshCodex);
  assert.equal(store.resumable().codex, false, "fresh launch removes prior id");
  assert.equal(await store.discover(dir, root), false, "prior launch tag cannot be reused");
  writeFileSync(join(data, "sessions.json"), "broken");
  assert.equal(createSessionStore(data).resumable().codex, false);
  console.log("SESSIONS OK (persistence, fresh launch, tagged ownership, ambiguity)");
} finally { rmSync(dir, { recursive: true, force: true }); }
